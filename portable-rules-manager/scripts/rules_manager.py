def tool_owns_path(tool: str, path: str) -> bool:
    for pattern in TOOL_GENERATED_PATHS[tool]:
        if pattern.endswith("/"):
            if path.startswith(pattern):
                return True
        elif pattern.startswith("*/"):
            if path.endswith(pattern[1:]) and len(path) > len(pattern[1:]):
                return True
        elif path == pattern:
            return True
    return False


def strip_generated_wrapper(text: str) -> str:
    if text.startswith("---\n"):
        end = text.find("\n---\n", 3)
        if end != -1:
            text = text[end + len("\n---\n"):]
    if HEADER in text:
        text = text.replace(HEADER, "", 1)
    return text.strip()


def split_rule_blocks(text: str) -> tuple[str, list[tuple[str, str]]]:
    """Split a merged generated file into (preamble, [(rule_id, body)])."""
    marks = list(RULE_MARKER.finditer(text))
    if not marks:
        return text, []
    preamble = text[: marks[0].start()]
    blocks = []
    for i, mark in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        blocks.append((mark.group(1), text[mark.end():end].strip()))
    return preamble, blocks


def split_index_block(text: str) -> tuple[str, str | None]:
    """Remove the generated rules-index region; return (rest, index_block or None)."""
    begin, end = text.find(INDEX_BEGIN), text.find(INDEX_END)
    if begin == -1 or end == -1 or end < begin:
        return text, None
    return text[:begin] + text[end + len(INDEX_END):], text[begin:end + len(INDEX_END)]


def do_harvest(root: Path, args: argparse.Namespace) -> int:
    raw = args.tools
    if raw in ("all", "configured") or "," in raw or not raw:
        raise ValueError("harvest 一次只回写一个工具；请传 --tools <单个工具>，如 --tools trae")
    tool = selected_tools(raw, {"targets": list(TOOLS)})[0]
    manifest_path = root / ".ai-rules" / "manifest.json"
    if not manifest_path.is_file():
        raise ValueError("缺少 .ai-rules/manifest.json；先 init 并 sync")
    m = read_json(manifest_path)
    errors = validate(root, m)
    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        return 2
    rules_by_id = {r["id"]: r for r in m["rules"]}
    state = get_state(root)
    expected = render(root, m, [tool])
    # action: (status, rule_id_or_name, path, new_body)
    actions: list[tuple[str, str, str, str | None]] = []
    for path in sorted(p for p in state if tool_owns_path(tool, p)):
        target = within(root, path)
        if not target.is_file() or target.is_symlink():
            actions.append(("MISSING", "", path, None))
            continue
        disk = target.read_text(encoding="utf-8")
        if state.get(path) == sha(disk):
            # 仅清单变化（索引落后）不算手改：提示重新同步，而不是 ORPHAN。
            if path == "AGENTS.md" and path in expected:
                _, idx_disk_fast = split_index_block(split_rule_blocks(disk)[0])
                _, idx_exp_fast = split_index_block(split_rule_blocks(expected[path])[0])
                if idx_exp_fast is not None and idx_disk_fast != idx_exp_fast:
                    print(f"INDEX-DIFF      {path}（规则索引区落后于清单，运行 sync --tools {tool} --apply 刷新，不算手改）")
            actions.append(("UNCHANGED", "", path, None))
            continue
        if any(path.startswith(d) for d in SINGLE_RULE_DIRS):
            match = SINGLE_RULE_NAME.fullmatch(PurePosixPath(path).name)
            rid = match.group(1).upper() if match else None
            if not rid or rid not in rules_by_id:
                actions.append(("UNKNOWN-RULE", rid or PurePosixPath(path).name, path, None))
                continue
            body = strip_generated_wrapper(disk)
            if body != rule_body(root, rules_by_id[rid]):
                actions.append(("HARVEST", rid, path, body))
            else:
                actions.append(("UNCHANGED", rid, path, None))
            continue
        # Merged file: split by rule-id markers, compare preamble and each block.
        # The generated rules-index region lives in the preamble; it is compared with the
        # index stripped out, so a manifest-only change is INDEX-DIFF, not a hand edit.
        pre_disk_raw, blocks_disk = split_rule_blocks(disk)
        exp = expected.get(path)
        pre_exp_raw, exp_blocks_list = split_rule_blocks(exp) if exp is not None else (None, [])
        exp_blocks = dict(exp_blocks_list)
        pre_disk, idx_disk = split_index_block(pre_disk_raw)
        pre_exp, idx_exp = split_index_block(pre_exp_raw or "")
        if exp is None or pre_disk.strip() != pre_exp.strip():
            actions.append(("ORPHAN", "", path, None))
        elif idx_exp is not None and idx_disk != idx_exp:
            print(f"INDEX-DIFF      {path}（规则索引区落后于清单，运行 sync --tools {tool} --apply 刷新，不算手改）")
        for rid, body in blocks_disk:
            if rid not in rules_by_id or rid not in exp_blocks:
                actions.append(("UNKNOWN-RULE", rid, path, None))
            elif body != rule_body(root, rules_by_id[rid]):
                actions.append(("HARVEST", rid, path, body))
            else:
                actions.append(("UNCHANGED", rid, path, None))
    for status, rid, path, _ in actions:
        print(f"{status:14} {rid or '-':35} {path}")
    harvests = [a for a in actions if a[0] == "HARVEST"]
    skipped = [a for a in actions if a[0] in ("ORPHAN", "UNKNOWN-RULE")]
    if not args.apply:
        print("预览完成：没有写入文件。添加 --apply 才回写到 .ai-rules 源文件。")
        return 0
    if not harvests:
        print("没有可回写的规则改动。")
        return 0
    timestamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S-%f") + "-harvest"
    for _, rid, _, body in harvests:
        rule = rules_by_id[rid]
        src = within(root / ".ai-rules", rule["file"])
        backup = within(root / ".ai-rules" / "backups" / timestamp / ".ai-rules", rule["file"])
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, backup)
        src.write_text(body.strip() + "\n", encoding="utf-8")
    # Re-render this tool so generated files match updated sources immediately.
    new_outputs = render(root, m, [tool])
    new_state = dict(state)
    for path, content in new_outputs.items():
        dest = within(root, path)
        if dest.is_file() and not dest.is_symlink() and dest.read_text(encoding="utf-8") != content:
            backup_file(root, path, timestamp)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
        new_state[path] = sha(content)
    save_state(root, new_state)
    print(f"已回写 {len(harvests)} 条规则并重渲染 {tool} 的 {len(new_outputs)} 个生成文件；备份: .ai-rules/backups/{timestamp}")
    if skipped:
        print("注意：ORPHAN/UNKNOWN-RULE 内容未回写；被重渲染覆盖的生成文件原件已保存在备份目录。")
    return 0


def docs_outputs(root: Path, m: dict[str, Any]) -> dict[str, str]:
    """docs/rules/ 人读规范库：按源文件目录分类镜像 + 索引；工具无关，不参与 harvest。"""
    active = sorted((r for r in m["rules"] if r["enabled"]), key=lambda x: x["id"])
    if not active:
        raise ValueError("没有启用的规则；先 new-rule，或在 manifest 中人工启用待审候选")
    outputs: dict[str, str] = {}
    placed: dict[str, str] = {}
    for r in active:
        path = "docs/rules/" + r["file"]
        if path in placed:
            raise ValueError(f"docs/rules 导出目标冲突: {path}（{placed[path]} 与 {r['id']} 共用同一源文件，请先拆分）")
        if path == "docs/rules/index.md":
            raise ValueError("规则源文件 index.md 会覆盖 docs/rules/index.md 索引，请改名")
        placed[path] = r["id"]
        meta = (f"<!-- rule-id: {r['id']} | layer: {r.get('layer', 'domain')} | strength: {r.get('strength', 'must')} "
                f"| anchor: {r['anchor']} | globs: {', '.join(r['globs'])} -->")
        outputs[path] = HEADER + "\n" + meta + "\n\n" + rule_body(root, r) + "\n"
    project = m.get("project", {}).get("name", root.name)
    lines = [f"# {project} · 规则文档索引", "", "本目录由 portable-rules-manager export-docs 生成，是工具无关的人读规范库；权威内容在 .ai-rules/，修改源后重新导出。", "AI 按任务按需读取下表中的具体文件，避免全量加载。", ""]
    by_cat: dict[str, list[dict[str, Any]]] = {}
    for r in active:
        by_cat.setdefault(r["file"].split("/")[0] if "/" in r["file"] else "misc", []).append(r)
    for cat in sorted(by_cat):
        lines += [f"## {cat}", "", "| 规则 | 说明 | 作用域 | 文件 |", "| --- | --- | --- | --- |"]
        for r in by_cat[cat]:
            desc = str(r.get("description") or r["id"]).replace("|", "\\|").replace("\n", " ")
            doc = "docs/rules/" + r["file"]
            lines.append(f"| {r['id']} | {desc} | `{r['globs'][0]}` | [{doc}]({doc}) |")
        lines.append("")
    outputs["docs/rules/index.md"] = managed("\n".join(lines))
    return outputs


