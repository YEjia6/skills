def package_version() -> str:
    """安装包版本以 VERSION 文件为准，缺失时回退到内置常量。"""
    try:
        return (Path(__file__).resolve().parent.parent / "VERSION").read_text(encoding="utf-8").strip() or VERSION
    except OSError:
        return VERSION


def read_json(path: Path) -> dict[str, Any]:
    try:
        result = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        raise ValueError(f"无法读取 JSON {path}: {exc}") from exc
    if not isinstance(result, dict):
        raise ValueError(f"JSON 顶层必须是对象: {path}")
    return result


def dump_json(data: Any) -> str:
    return json.dumps(data, ensure_ascii=False, sort_keys=False, indent=2) + "\n"


def sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def relpath(path: str, *, allow_dot: bool = False) -> str:
    if not isinstance(path, str) or not path or "\\" in path or "\x00" in path:
        raise ValueError(f"路径必须是规范 POSIX 相对路径: {path!r}")
    if path == "." and allow_dot:
        return path
    parts = PurePosixPath(path).parts
    if path.startswith("/") or any(p in {".", ".."} for p in path.split("/")) or not parts or ":" in parts[0]:
        raise ValueError(f"拒绝绝对路径或路径穿越: {path}")
    # No glob in output paths; globs validated separately.
    return str(PurePosixPath(*parts))


def within(root: Path, relative: str) -> Path:
    relpath(relative)
    base = root.resolve()
    candidate = root / relative
    if not candidate.resolve().is_relative_to(base):
        raise ValueError(f"禁止符号链接逃逸到仓库外: {relative}")
    return candidate


def link_escapes(root: Path, p: Path) -> bool:
    """符号链接，或解析后逃逸 root 的链接（含 Windows 目录联接 junction）。"""
    if p.is_symlink():
        return True
    try:
        return not p.resolve().is_relative_to(root.resolve())
    except OSError:
        return True


def safe_glob(pattern: str) -> str:
    if not isinstance(pattern, str) or not pattern or "\\" in pattern or pattern.startswith("/") or "\x00" in pattern:
        raise ValueError(f"无效 glob: {pattern!r}")
    if any(p in {"..", "."} for p in pattern.split("/")) or pattern.startswith("!") or any(ord(ch) < 32 for ch in pattern) or "," in pattern:
        raise ValueError(f"glob 不允许路径穿越或否定表达式: {pattern}")
    return pattern


def scan_repo(root: Path) -> dict[str, Any]:
    root = root.resolve()
    counts: dict[str, int] = {}
    dirs: dict[str, tuple[list[str], list[str]]] = {}
    visited = 0
    for parent, children, filenames in os.walk(root, topdown=True, followlinks=False):
        base = Path(parent)
        depth = len(base.relative_to(root).parts)
        children[:] = sorted(c for c in children if c not in IGNORE_DIRS and not c.startswith(".") and not (base / c).is_symlink()) if depth < 6 else []
        filenames = sorted(filenames)
        visited += 1
        if visited > 3500:
            break
        rel = base.relative_to(root).as_posix()
        named = [f for f in filenames if f in MARKERS or f.endswith((".csproj", ".sln"))]
        hints = [f for f in filenames if f.endswith((".qml", ".ui"))][:8]
        if named or hints or (depth >= 1 and base.name.lower() in MAPPING):
            dirs[rel] = (named, hints)
        for f in filenames:
            suffix = Path(f).suffix.lower()
            if suffix in {".py", ".ts", ".tsx", ".js", ".jsx", ".vue", ".go", ".rs", ".java", ".kt", ".swift", ".dart", ".cpp", ".c", ".cs", ".qml"}:
                counts[suffix[1:]] = counts.get(suffix[1:], 0) + 1

    candidates = []
    for rel, (markers, hints) in dirs.items():
        path = Path(rel)
        parts = [p.lower() for p in path.parts]
        matches = [MAPPING[x] for x in parts if x in MAPPING]
        kind = matches[-1] if matches else None
        reason: list[str] = []
        confidence = "medium"
        if kind:
            reason.append("命名目录: " + "/".join(parts))
            confidence = "medium"
        if "pubspec.yaml" in markers:
            kind, confidence = "mobile", "high"
            reason.append("Flutter pubspec.yaml")
        if hints and ("hmi" in parts or "scada" in parts):
            kind, confidence = "hmi", "high"
            reason.append("HMI 目录 + Qt 文件")
        if "package.json" in markers:
            package = root / rel / "package.json"
            try:
                pdata = json.loads(package.read_text(encoding="utf-8"))
                deps = {**pdata.get("dependencies", {}), **pdata.get("devDependencies", {})}
                frameworks = [x for x in ("react", "vue", "next", "@angular/core", "svelte", "vite", "react-native", "expo") if x in deps]
                if frameworks:
                    reason.append("依赖: " + ", ".join(frameworks))
                    if "react-native" in deps or "expo" in deps:
                        kind, confidence = "mobile", "high"
                    elif kind is None:
                        kind, confidence = "web", "medium"
            except (OSError, ValueError, TypeError, AttributeError):
                reason.append("package.json 未能完整解析")
        if "pyproject.toml" in markers or "go.mod" in markers or "pom.xml" in markers:
            if kind is None and any(x in parts for x in ("services", "service", "api", "backend")):
                kind, confidence = "backend", "medium"
        if kind:
            candidates.append({"path": rel, "kind": kind, "confidence": confidence, "evidence": sorted(set(reason + markers + hints))[:10]})
    # Prefer leaf module directories over superficial parent containers.
    candidates.sort(key=lambda x: (len(Path(x["path"]).parts), x["path"]))
    modules = []
    for c in candidates:
        if c["path"] == "." and any(k["path"] != "." for k in candidates):
            continue
        if any(c["path"] != m["path"] and (c["path"] == "." or m["path"].startswith(c["path"] + "/")) and c["kind"] == m["kind"] for m in candidates):
            continue
        if c["path"] not in [m["path"] for m in modules]:
            modules.append(c)
    return {"project": root.name, "languages_by_file_count": counts, "modules": sorted(modules, key=lambda x: x["path"]), "scan_limited": visited > 3500, "notes": ["启发式扫描结果仅为候选；务必审核 HMI 与混合项目的目录、技术栈、UI 场景", "扫描只读取文件名与 package.json 依赖信息，不读取业务代码内容"]}


def choose_feature_dir(root: Path, module: str, kinds: tuple[str, ...]) -> str | None:
    for parent in ("src/features", "src/pages", "src/views", "features", "pages", "views", "app"):
        for part in kinds:
            target = PurePosixPath(module) / parent / part if module != "." else PurePosixPath(parent) / part
            if (root / str(target)).is_dir():
                return str(target)
    return None


def new_manifest(root: Path, report: dict[str, Any]) -> dict[str, Any]:
    rules: list[dict[str, Any]] = []
    def add(rule_id: str, file: str, anchor: str, *, enabled: bool = True, desc: str = "", layer: str = "domain", strength: str = "must", conflict_group: str = ""):
        rules.append({"id": rule_id, "file": file, "anchor": anchor, "globs": ["**/*"] if anchor == "." else [f"{anchor}/**/*"], "excludes": [], "enabled": enabled, "description": desc, "layer": layer, "strength": strength, "conflict_group": conflict_group})
    add("CORE-ENGINEERING", "core/engineering.md", ".", desc="全仓库工程底线", layer="core")
    for m in report["modules"]:
        path, kind = m["path"], m["kind"]
        code = re.sub(r"[^A-Z0-9]+", "-", path.upper()).strip("-") or "ROOT"
        if kind == "web":
            add(f"WEB-BASELINE-{code}", "domains/web/ui-baseline.md", path, desc="Web 交互与可用性底线")
            regular = choose_feature_dir(root, path, ("business", "regular", "admin", "management"))
            analytics = choose_feature_dir(root, path, ("analytics", "analysis", "dashboard", "charts", "statistics"))
            if regular:
                add(f"WEB-REGULAR-{code}", "domains/web/regular-ui.md", regular, desc="仅普通 Web 业务页面视觉偏好", layer="scenario", strength="should", conflict_group="web-visual-mode")
            if analytics:
                add(f"WEB-ANALYTICS-{code}", "domains/web/analytics.md", analytics, desc="图表分析专用规则", layer="scenario", conflict_group="web-visual-mode")
            if not (regular or analytics):
                # Scope of design preference uncertain: no overly broad rule.
                add(f"WEB-REGULAR-REVIEW-{code}", "domains/web/regular-ui.md", path, enabled=False, desc="待确认普通业务页面路径；默认禁用，避免误伤图表分析", layer="scenario", strength="should", conflict_group="web-visual-mode")
        elif kind == "backend":
            add(f"BACKEND-{code}", "domains/backend/api.md", path, desc="后端 API 约束")
        elif kind == "mobile":
            add(f"MOBILE-{code}", "domains/mobile/interaction.md", path, desc="移动端交互")
        elif kind == "hmi":
            add(f"HMI-{code}", "domains/hmi/interaction.md", path, desc="工业 HMI 交互")
    # Pre-existing user rules: index as disabled review proposals instead of assuming scope.
    seen = {x["file"] for x in rules}
    for rule_file in sorted((root / ".ai-rules").rglob("*.md")):
        if not rule_file.is_file() or rule_file.is_symlink():
            continue
        rel = rule_file.relative_to(root / ".ai-rules").as_posix()
        if rel in seen or rel.startswith(("proposals/", "backups/")):
            continue
        name = re.sub("[^A-Z0-9]+", "-", Path(rel).stem.upper()).strip("-")
        add(f"LEGACY-REVIEW-{name}-{len(rules)}", rel, ".", enabled=False, desc="待人工确认适用范围的历史规则；默认禁用", layer="scenario", strength="should")
    return {"schema_version": 1, "project": {"name": root.name, "scan": report}, "targets": list(TOOLS), "rules": rules}


def validate(root: Path, manifest: dict[str, Any]) -> list[str]:
    errors = []
    if manifest.get("schema_version") != 1:
        errors.append("schema_version 目前必须为 1")
    seen = set()
    for r in manifest.get("rules", []):
        try:
            rid = r["id"]
            if not isinstance(rid, str) or not re.fullmatch(r"[A-Z][A-Z0-9-]*", rid):
                raise ValueError("规则 ID 必须是大写字母/数字/连字符")
            if rid in seen:
                raise ValueError("重复规则 ID")
            seen.add(rid)
            file = relpath(r["file"])
            rule_path = within(root / ".ai-rules", file)
            if not rule_path.is_file() or rule_path.is_symlink():
                raise ValueError("规则正文不存在或是符号链接")
            anchor = relpath(r["anchor"], allow_dot=True)
            if anchor != ".":
                anchor_dir = root / anchor
                if not anchor_dir.is_dir() or anchor_dir.is_symlink() or not anchor_dir.resolve().is_relative_to(root.resolve()):
                    raise ValueError(f"anchor 不存在或不安全: {anchor}")
            globs = r["globs"]
            if not isinstance(globs, list) or not globs:
                raise ValueError("globs 不能为空")
            for g in globs:
                safe_glob(g)
            for e in r.get("excludes", []):
                safe_glob(e)
            if not isinstance(r.get("enabled"), bool):
                raise ValueError("enabled 必须是 true/false")
            if r.get("layer", "domain") not in ("core", "domain", "scenario", "local"):
                raise ValueError("layer 必须是 core/domain/scenario/local")
            if r.get("strength", "must") not in ("must", "should", "may"):
                raise ValueError("strength 必须是 must/should/may")
            cg = r.get("conflict_group", "")
            if not isinstance(cg, str) or (cg and not re.fullmatch(r"[a-z0-9-]+", cg)):
                raise ValueError("conflict_group 应为空或 kebab-case")
            if r.get("excludes") and r.get("enabled"):
                errors.append(f"{rid}: 原生规则适配器无法可靠表达 excludes；请改用互不重叠的正向 globs，或先禁用规则")
            # For nested AGENTS/GEMINI, require strict scope to avoid accidentally applying broad rules.
            expected = "**/*" if anchor == "." else f"{anchor}/**/*"
            if r.get("enabled") and globs != [expected]:
                errors.append(f"{rid}: 嵌套 AGENTS/GEMINI 无法严格表达自定义 glob；请把 anchor 指向独立目录并使用 {expected}，或先禁用")
        except (KeyError, TypeError, ValueError) as e:
            errors.append(f"{r.get('id', '<unknown>')}: {e}")
    # Reject overlap in mutually exclusive design modes. This is a static directory check;
    # different conflict_group values can still be semantically contradictory and require review.
    exclusive: dict[str, list[dict[str, Any]]] = {}
    for r in manifest.get("rules", []):
        if r.get("enabled") and r.get("conflict_group"):
            exclusive.setdefault(r["conflict_group"], []).append(r)
    for group, rules in exclusive.items():
        for i, a in enumerate(rules):
            for b in rules[i+1:]:
                x, y = a.get("anchor", "."), b.get("anchor", ".")
                if x == "." or y == "." or x == y or x.startswith(y + "/") or y.startswith(x + "/"):
                    errors.append(f"互斥规则冲突 {group}: {a['id']} 与 {b['id']} 的目录重叠 ({x} / {y})")
    return errors


def managed(body: str) -> str:
    return HEADER + "\n\n" + body.strip() + "\n"


def rule_body(root: Path, rule: dict[str, Any]) -> str:
    return within(root / ".ai-rules", rule["file"]).read_text(encoding="utf-8").strip()


INDEX_BEGIN = "<!-- rules-index:begin -->"
INDEX_END = "<!-- rules-index:end -->"


def rules_index_section(manifest: dict[str, Any]) -> str:
    """生成根 AGENTS.md 的规则索引区：统一入口 + 按需加载指路牌。"""
    rows = []
    for r in sorted((x for x in manifest["rules"] if x["enabled"]), key=lambda x: x["id"]):
        desc = str(r.get("description") or r["id"]).replace("|", "\\|").replace("\n", " ")
        rows.append(f"| {r['id']} | {r.get('layer', 'domain')}/{r.get('strength', 'must')} | {desc} | `{r['globs'][0]}` | `.ai-rules/{r['file']}` |")
    lines = [
        "## 规则索引（按需读取）",
        "",
        "改动命中下表「作用域」的文件前，先读取对应源文件再动手；权威清单是 `.ai-rules/manifest.json`。",
        "",
        "| 规则 | 层级/强度 | 说明 | 作用域 | 源文件 |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += rows
    return INDEX_BEGIN + "\n" + "\n".join(lines) + "\n" + INDEX_END


def render(root: Path, manifest: dict[str, Any], tools: list[str]) -> dict[str, str]:
    active = [r for r in manifest["rules"] if r["enabled"]]
    core = [r for r in active if r["anchor"] == "."]
    by_anchor: dict[str, list[dict[str, Any]]] = {}
    for r in active:
        by_anchor.setdefault(r["anchor"], []).append(r)
    outputs: dict[str, str] = {}
    project = manifest.get("project", {}).get("name", root.name)
    def combine(rules: list[dict[str, Any]], title: str, index: str | None = None) -> str:
        chunks = [f"# {title}", "", "以下内容由 .ai-rules/manifest.json 与规则源文件生成。修改源文件后重新运行同步。", "", "规则冲突原则：工程安全底线始终有效；同一设计维度的场景专用规范替代一般偏好；不能自动确定时报告冲突。"]
        if index:
            # 索引必须位于首个 rule-id 锚点之前（前言区），否则会被按锚点拆分进最后一条规则。
            chunks += ["", index]
        for r in rules:
            chunks += ["", f"<!-- rule-id: {r['id']} -->", rule_body(root, r)]
        return "\n".join(chunks)
    # AGENTS is used as base by Codex/Cursor/Windsurf/DeepSeek Harness (dsh) and imported by Claude/Gemini.
    # dsh needs no extra outputs: agent-instructions loads the shared agents-root AGENTS.md.
    if tools:
        outputs["AGENTS.md"] = managed(combine(core, f"{project} · Agent 全局规则", index=rules_index_section(manifest)))
        for anchor, group in sorted(by_anchor.items()):
            if anchor != ".":
                outputs[f"{anchor}/AGENTS.md"] = managed(combine(group, f"{anchor} · 目录级规则"))

    if "cursor" in tools:
        for r in active:
            if r["anchor"] == ".":
                continue  # Core is already in AGENTS.md, avoid duplicate Always rule.
            description = str(r.get("description", r["id"])).replace("\n", " ").replace('"', "'")
            globs = ",".join(r["globs"])
            fm = f'---\ndescription: "{description}"\nglobs: "{globs}"\nalwaysApply: false\n---\n\n'
            outputs[f".cursor/rules/ai-{r['id'].lower()}.mdc"] = fm + managed(rule_body(root, r))
    if "claude" in tools:
        outputs["CLAUDE.md"] = managed("@AGENTS.md\n\n如使用 Claude Code，目录相关细则见 .claude/rules/；不要把业务页视觉偏好套用于图表分析区。")
        for r in active:
            if r["anchor"] == ".":
                continue
            paths = "\n".join(f'  - "{g}"' for g in r["globs"])
            outputs[f".claude/rules/ai-{r['id'].lower()}.md"] = f"---\npaths:\n{paths}\n---\n\n" + managed(rule_body(root, r))
    if "gemini" in tools:
        outputs["GEMINI.md"] = managed("# Gemini CLI 项目规则\n\n@./AGENTS.md\n")
        for anchor in by_anchor:
            if anchor != ".":
                outputs[f"{anchor}/GEMINI.md"] = managed("# Gemini CLI 目录规则\n\n@./AGENTS.md\n")
    if "copilot" in tools:
        outputs[".github/copilot-instructions.md"] = managed(combine(core, f"{project} · Copilot 仓库规则"))
        for r in active:
            if r["anchor"] == ".":
                continue
            globs = ",".join(r["globs"])
            fm = f'---\napplyTo: "{globs}"\n---\n\n'
            outputs[f".github/instructions/ai-{r['id'].lower()}.instructions.md"] = fm + managed(rule_body(root, r))
    if "windsurf" in tools:
        # AGENTS.md is first-class native scoped rules in current Cascade/Devin Desktop.
        # Do not add .devin/rules duplicates by default.
        pass
    if "trae" in tools:
        # Trae loads both root AGENTS.md (carrying core rules, generated by the shared
        # AGENTS block above) and .trae/rules/*.md. Only domain rules go to .trae/rules/
        # so core content is not loaded twice in the same session.
        for r in active:
            if r["anchor"] == ".":
                continue
            outputs[f".trae/rules/ai-{r['id'].lower()}.md"] = managed(rule_body(root, r))
    return outputs


def get_state(root: Path, filename: str = ".generated-state.json") -> dict[str, str]:
    file = root / ".ai-rules" / filename
    if not file.is_file():
        return {}
    state = read_json(file)
    if state.get("managed_by") != MANAGER or not isinstance(state.get("files"), dict):
        raise ValueError("生成状态无效：" + filename)
    return state["files"]


def save_state(root: Path, state: dict[str, str], filename: str = ".generated-state.json") -> None:
    (root / ".ai-rules" / filename).write_text(dump_json({"managed_by": MANAGER, "files": dict(sorted(state.items()))}), encoding="utf-8")


def sync_report(root: Path, outputs: dict[str, str], state: dict[str, str]) -> list[tuple[str, str]]:
    results = []
    for path, content in sorted(outputs.items()):
        existing = within(root, path)
        if existing.exists() or existing.is_symlink():
            if not existing.is_file() or existing.is_symlink():
                action = "CONFLICT (不是普通文件或是符号链接)"
            else:
                old = existing.read_text(encoding="utf-8")
                if old == content:
                    action = "UNCHANGED"
                elif state.get(path) == sha(old):
                    action = "UPDATE"
                else:
                    action = "CONFLICT (未托管或已手工修改)"
        else:
            action = "CREATE"
        results.append((action, path))
    return results


def backup_file(root: Path, relative: str, timestamp: str) -> None:
    source = within(root, relative)
    dest = within(root / ".ai-rules" / "backups" / timestamp, relative)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, dest)


def selected_tools(raw: str, manifest: dict[str, Any]) -> list[str]:
    wanted = manifest.get("targets", list(TOOLS)) if raw == "configured" else list(TOOLS) if raw == "all" else [x.strip() for x in raw.split(",")]
    invalid = [x for x in wanted if x not in TOOLS]
    if invalid or not wanted:
        raise ValueError("未知工具：" + ",".join(invalid) + "；可选 " + ",".join(TOOLS))
    return list(dict.fromkeys(wanted))


def do_sync(root: Path, args: argparse.Namespace, *, check: bool = False) -> int:
    manifest_path = root / ".ai-rules" / "manifest.json"
    if not manifest_path.is_file():
        raise ValueError("先执行 init，或在 .ai-rules/manifest.json 中定义规则")
    m = read_json(manifest_path)
    errors = validate(root, m)
    if errors:
        for e in errors:
            print("ERROR:", e, file=sys.stderr)
        return 2
    tools = selected_tools(args.tools, m)
    outputs = render(root, m, tools)
    state = get_state(root)
    results = sync_report(root, outputs, state)
    for status, path in results:
        print(f"{status:43} {path}")
    stale = set(state) - set(outputs)
    # If tool subset specified, stale may be from another adapter; do not prune in that case.
    if args.tools not in ("configured", "all"):
        stale = set()
    if stale:
        print("STALE (需使用 --prune 才移除):", ", ".join(sorted(stale)))
    if check:
        drift = any(x[0] != "UNCHANGED" for x in results) or bool(stale)
        print("CHECK:", "FAIL: 输出存在漂移或缺失" if drift else "PASS: 所有目标均已同步")
        return 1 if drift else 0
    if not args.apply:
        print("预览完成：没有写入文件。添加 --apply 才同步；已有手写文件默认拒绝覆盖。")
        return 0
    conflicts = [(s, p) for s, p in results if s.startswith("CONFLICT")]
    symlink_conflicts = [(s, p) for s, p in conflicts if link_escapes(root, root / p)]
    if symlink_conflicts:
        print("拒绝覆盖符号链接或逃逸仓库的链接（即使使用 --force）；请手工检查目标路径。", file=sys.stderr)
        return 3
    if conflicts and not args.force:
        print("存在冲突文件，已停止全部同步。可先人工迁移，或明确指定 --force（自动备份）。", file=sys.stderr)
        return 3
    timestamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    new_state = dict(state)
    for status, path in results:
        if status == "UNCHANGED":
            new_state[path] = sha(outputs[path])
            continue
        destination = within(root, path)
        if destination.exists() or destination.is_symlink():
            backup_file(root, path, timestamp)
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Writing only plain files; no symlinks; no out-of-tree destinations.
        destination.write_text(outputs[path], encoding="utf-8")
        new_state[path] = sha(outputs[path])
    if args.prune:
        for path in sorted(stale):
            target = within(root, path)
            if target.exists() and target.is_file() and not target.is_symlink():
                old = target.read_text(encoding="utf-8")
                if state[path] != sha(old) and not args.force:
                    print("保留已手改的旧输出:", path)
                    continue
                backup_file(root, path, timestamp)
                target.unlink()
            new_state.pop(path, None)
    save_state(root, new_state)
    print("同步完成；备份目录（如发生覆盖）:", f".ai-rules/backups/{timestamp}")
    return 0


